#include <iostream>

/**
 * C++ 运算符优先级
 * 1. 括号 ()、下标 []、成员访问 . ->、函数调用 ()、类型转换 (type)、后缀自增自减 ++ --、条件运算符 ?:
 * 2. 一元运算符 + - ! ~ ++ -- (前缀)、类型转换 (type)、取地址 &、取反 *、sizeof、new、delete
 * 3. 乘法、除法、取模 * / %
 * 4. 加法、减法 + -
 * 5. 移位 << >>
 * 6. 关系运算符 < <= > >=
 * 7. 相等运算符 == !=
 * 8. 位与 &
 * 9. 位异或 ^
 * 10. 位或 |
 * 11. 逻辑与 &&
 * 12. 逻辑或 ||
 * 13. 条件运算符 ?:
 * 14. 赋值运算符 = += -= *= /= %= <<= >>= &= ^= |=
 * 15. 逗号运算符 ,
 * 
 * 不同编译器可能对某些运算符的优先级有微小差异，尤其是位运算符和逻辑运算符之间的优先级。
 * 参考：
 * - C++ 标准（C++20）中定义了运算符的优先级和结合性。
 * - 不同编译器的文档中也会列出运算符优先级表，例如 GCC、Clang、MSVC 等。
 */
int main()
{
    /* 负数取余 */
    int a = -10;
    int b = 3;
    int c = a % b; // 结果为 -1，因为 -10 = (-4) * 3 + (-1)
    std::cout << "-10 % 3 = " << c << std::endl;
    std::cout << "-10 / 3 = " << (a / b) << std::endl; // 输出 -3

    /* 逻辑运算符优先级 */
    bool x = true;
    bool y = false;
    bool z = x && y || !x; // 结果为 true，因为 && 的优先级高于 ||，!x 的优先级最高
    std::cout << "x && y || !x = " << z << std::endl;

    return 0;
}